type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number | string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean; color?: string };
export type LucideIcon = ReturnType<typeof make>;
export type LucideProps = IconProps;

function make(icon: IconDefinition, name: string) {
  const C = forwardRef<SVGSVGElement, IconProps>(({ size = 24, strokeWidth: _sw, absoluteStrokeWidth: _a, color, style, className, ...rest }, ref) => (
    <FontAwesomeIcon ref={ref} icon={icon} className={className} aria-hidden={(rest as any)["aria-hidden"] ?? true} {...(rest as any)}
      style={{ width: size, height: size, color, flexShrink: 0, ...(style as CSSProperties) }} />
  ));
  C.displayName = name;
  return C;
}

